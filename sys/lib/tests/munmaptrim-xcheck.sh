#!/bin/sh
# munmaptrim-xcheck.sh -- extract the real `p9_munmap' and its table out
# of libap, compile them with gcc beside the harness, and run it.
#
#	sh munmaptrim-xcheck.sh
#
# ***THE EXTRACTION IS THE POINT.*** This tree's rule is to replicate the
# code IN the tree, line by line, and not the code you remember -- a
# probe written from a recollection of `DoCopyFile' once skipped its
# `unlink(dst)' and so reported 0 failures for a copy that did not work.
# So nothing here is transcribed: the two ranges are cut out of
# `__p9_syscall.c' by MARKER, not by line number, which also means an
# edit above them cannot silently shift what is tested.
#
# `p9_mmap_tracked' is deliberately NOT extracted: it calls
# `p9_mmap_impl', which calls `_SEGATTACH', and the harness fills the
# table itself so the addresses in the output mean something. The
# bookkeeping under test is entirely in `p9_munmap'.
#
# The extraction GATES: if either marker stops matching, the script says
# so and stops, rather than compiling half the function and reporting a
# clean number.

set -e

# This file is four levels below the repository root.
ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
SRC=$ROOT/sys/src/ape/lib/ap/plan9/__p9_syscall.c
OUT=$(dirname "$0")/munmaptrim-extract.h

if [ ! -f "$SRC" ]; then
	echo "munmaptrim-xcheck: no $SRC -- is ROOT wrong?" >&2
	exit 2
fi

{
	echo "/* GENERATED by munmaptrim-xcheck.sh -- do not edit. */"
	grep '^#define SEG_THRESHOLD' "$SRC"
	grep '^#define MMAP_PAGE' "$SRC"
	sed -n '/^static struct MmapEntry {/,/^static int mmap_table_cap/p' "$SRC"
	awk '
		/^p9_mmap_impl\(void \*addr, size_t len/    { print prev; inf = 1 }
		/^p9_mmap_tracked\(void \*addr, size_t len/ { print prev; inf = 1 }
		/^p9_munmap\(void \*addr, size_t len\)$/    { print prev; inf = 1 }
		inf { print }
		inf && /^}$/ { inf = 0 }
		{ prev = $0 }
	' "$SRC"
} > "$OUT"

# gate: every piece must be there, and the DEFINES are part of it --
# the threshold decides which arm each case exercises, so a harness
# compiled without it would silently test one path twice.
for marker in '#define SEG_THRESHOLD' '#define MMAP_PAGE' 'struct MmapEntry' \
              'p9_mmap_impl' 'p9_mmap_tracked' 'p9_munmap'; do
	grep -q -- "$marker" "$OUT" || {
		echo "munmaptrim-xcheck: marker '$marker' did not match" >&2
		exit 2
	}
done
# the return types live on their own line above each name
[ "$(grep -c '^static void \*$' "$OUT")" -ge 1 ] || {
	echo "munmaptrim-xcheck: lost p9_mmap_impl's return type" >&2; exit 2; }
grep -q '^int$' "$OUT" || {
	echo "munmaptrim-xcheck: lost p9_munmap's return type" >&2; exit 2; }

cc=${CC:-gcc}
$cc -Wall -Wno-unused-function -o "$(dirname "$0")/munmaptrim-xcheck" \
	"$(dirname "$0")/munmaptrim-xcheck.c"
"$(dirname "$0")/munmaptrim-xcheck"
