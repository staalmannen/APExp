#!/bin/sh
#
# clisp-mirror.sh -- stage clisp's generated build tree on the BUILD HOST,
# so the host-built kencc can compile and inspect it.
#
#	sh clisp-mirror.sh            # stage into out/clisp
#	sh clisp-mirror.sh --flags    # print the compile flags and exit
#	sh clisp-mirror.sh --compile  # compile all 31 TUs; gates
#	eval "$(sh clisp-mirror.sh --flags)"; $CC6 -S $CFL out/clisp/spvw.c
#
# This exists because the same twelve commands have been retyped three
# times in three rounds. It depends on `hostkencc.sh' having run.
#
# ***THE `intparam.h' HERE IS A MODEL AND THAT IS THE WHOLE CAVEAT.***
# clisp's `configure' answers the integer widths by COMPILING AND RUNNING
# `intparam.c', so on the VM the answers are kencc's. Here the probe is
# built with gcc, which is LP64, and the one answer that differs is
# patched afterwards: `long_bitsize' 64 -> 32, `sizeof_long' and
# `alignment_long' 8 -> 4. **Everything else gcc and kencc agree on**
# (char 8, short 16, int 32, long long 64, pointer 64).
#
# *Leaving that patch out is not a small error.* `lispbibl.d:1180' picks
# `ULONGLONG' from `long_bitsize', so an unpatched LP64 `intparam.h'
# makes `uint64' -- and therefore `uintP', and therefore `oint', the type
# every CLISP object is -- `unsigned long', 32 bits wide under kencc.
# A whole round was spent reading a mirror in that state and concluding
# the object representation was broken; it was the mirror's, not the
# tree's. **A model that is wrong about the one thing under test is worse
# than no model.**
#
# What is sound here: preprocessing, compiling, diagnostics, generated
# code for width-dependent macros -- everything the three clisp bugs of
# this release were found with. What is NOT: anything that depends on a
# float format or a struct layout `floatparam.c' measured, since that
# file is gcc's answer untouched.
#
# **Compile with `-J -p', never bare `6c'.** `pcc' passes `-J' and bare
# `6c' does not, so without it every struct size differs from a real APE
# build -- `stream.d:17311' answers `duplicate cases in switch 8' because
# `sizeof(ffloatjanus)' is 4 under `-J' and 8 under the 9front rule.
# `--flags' prints the whole set so it cannot be got wrong by hand.

set -e

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../../.." && pwd)
CLISP=$ROOT/sys/src/external/clisp
SRC=$CLISP/src
OUT=$HERE/out/clisp
TOOLS=$HERE/out/clisp-tools

# `sys/lib/tests/hostkencc' is FOUR levels below the root; the guard is
# here because that count has been wrong in five instruments now.
test -f "$SRC/lispbibl.d" || { echo "clisp-mirror: no $SRC/lispbibl.d -- ROOT wrong" >&2; exit 2; }

CFL="-D__STDC__=1 -D_PLAN9_SOURCE -D_POSIX_SOURCE -D_BSD_EXTENSION"
CFL="$CFL -DENABLE_UNICODE -D__x86_64__"
CFL="$CFL -I$OUT -I$SRC -I$SRC/gllib -I$OUT/shadow"
CFL="$CFL -I$ROOT/amd64/include/ape -I$ROOT/sys/include/ape"

if [ "${1:-}" = "--flags" ]; then
	echo "CC6='$HERE/out/bin/6c -J -p'"
	echo "CFL='$CFL'"
	echo "PATH=\"$HERE/out/bin:\$PATH\"; export PATH"
	echo "export objtype=amd64"
	exit 0
fi

test -x "$HERE/out/bin/6c" || { echo "clisp-mirror: run hostkencc.sh first" >&2; exit 2; }

if [ "${1:-}" = "--compile" ]; then
	# Compile the 31 translation units `mkfile.cparts' names, plus
	# modules.c. `const if true/false' is filtered because the whole of
	# lispbibl is width-conditional and the compiler says so thousands
	# of times; anything else is a real diagnostic.
	eval "$(sh "$0" --flags)"
	ok=0; bad=0; fails=
	for f in spvw spvwtabf spvwtabs spvwtabo eval control encoding \
		 pathname stream socket io funarg array hashtabl list package \
		 record weak sequence charstrg debug error misc time predtype \
		 symbol lisparit i18n unixaux built; do
		kencc-cpp $CFL "$OUT/$f.c" > "$TOOLS/t.i" 2>/dev/null
		if $CC6 -c -o /dev/null "$TOOLS/t.i" 2>&1 |
		   grep -qvE 'const if (false|true)|^warning|^$'; then
			bad=$((bad+1)); fails="$fails $f"
		else ok=$((ok+1)); fi
	done
	kencc-cpp $CFL -DNO_CLISP_H "$SRC/modules.c" > "$TOOLS/t.i" 2>/dev/null
	if $CC6 -c -o /dev/null "$TOOLS/t.i" 2>&1 |
	   grep -qvE 'const if (false|true)|^warning|^$'; then
		bad=$((bad+1)); fails="$fails modules"
	else ok=$((ok+1)); fi
	echo "clisp-mirror: compiled $ok, errors $bad$fails"
	test "$bad" -eq 0
	exit
fi

mkdir -p "$TOOLS" "$OUT/shadow"

# 1. clisp's own .d -> .c converters. All three build with gcc.
for t in comment5 gctrigger varbrace; do
	test -x "$TOOLS/$t" || gcc -w -O1 -o "$TOOLS/$t" "$CLISP/utils/$t.c"
done

# 2. the configure outputs.
cp "$ROOT/sys/src/ape/cmd/clisp/config.h" "$OUT/config.h"
for h in unitypes uniwidth uniname; do cp "$SRC/gllib/$h.in.h" "$OUT/$h.h"; done
cat > "$OUT/cflags.h" <<'EOF'
/* generated by clisp-mirror.sh; only (sys::build-info) reads these */
#define CC "pcc"
#define CFLAGS ""
#define LDFLAGS ""
#define CLFLAGS ""
#define LIBS ""
#define CPPFLAGS ""
#define CPP "cpp"
#define CXX ""
#define CXXFLAGS ""
#define X_LIBS ""
EOF

# 3. intparam.h / floatparam.h -- see the caveat at the top.
gcc -w -DHAVE_LONG_LONG_INT -o "$TOOLS/intparam" "$SRC/intparam.c"
gcc -w -DHAVE_LONG_LONG_INT -o "$TOOLS/floatparam" "$SRC/floatparam.c"
( cd "$OUT" && "$TOOLS/intparam" intparam.h && "$TOOLS/floatparam" floatparam.h )
sed -i -e 's/^#define long_bitsize 64$/#define long_bitsize 32/' \
       -e 's/^#define sizeof_long 8$/#define sizeof_long 4/' \
       -e 's/^#define alignment_long 8$/#define alignment_long 4/' "$OUT/intparam.h"
grep -q '^#define long_bitsize 32$' "$OUT/intparam.h" || {
	echo "clisp-mirror: long_bitsize patch did not apply -- intparam.c output changed" >&2
	exit 1
}

# 4. `$objtype/include/ape/stddef_arch.h' includes "/sys/include/ape/stddef.h"
# by ABSOLUTE path, which does not exist here. One shadowing copy fixes it,
# and nothing else in APExp's headers needs help.
sed 's#"/sys/include/ape/#"#' "$ROOT/amd64/include/ape/stddef_arch.h" > "$OUT/shadow/stddef_arch.h"

# 5. the .d -> .c conversion, as `mkfile.rebuild' does it.
n=0
for f in "$SRC"/*.d; do
	b=$(basename "$f" .d)
	if [ "$b" = lispbibl ]; then
		"$TOOLS/comment5" "$f" | sed -e 's/^%% .*//' | "$TOOLS/gctrigger" | "$TOOLS/varbrace" > "$OUT/$b.c" 2>/dev/null
	else
		"$TOOLS/comment5" "$f" | "$TOOLS/gctrigger" | "$TOOLS/varbrace" > "$OUT/$b.c" 2>/dev/null
	fi
	test -s "$OUT/$b.c" || { echo "clisp-mirror: empty generation for $b" >&2; exit 1; }
	n=$((n+1))
done
"$TOOLS/comment5" "$SRC/lispbibl.d" | sed -e '/^%% /{s///p;d;}' -e '/^#line /!s/.*//' > "$OUT/gen.lispbibl.c"

echo "clisp-mirror: $n translation units staged in $OUT"
echo "clisp-mirror: eval \"\$(sh $0 --flags)\" to get \$CC6 and \$CFL"
